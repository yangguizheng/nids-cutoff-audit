


import csv
import math
import os

ROOT = "."
LIT = os.path.join(ROOT, "lit")


def wilson(k, n, z=1.959963985):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def pct(k, n):
    lo, hi = wilson(k, n)
    return "%d/%d = %.1f%% [%.1f, %.1f]" % (k, n, 100.0 * k / n if n else float("nan"),
                                            100 * lo, 100 * hi)


def main():
    rows = list(csv.DictReader(open(os.path.join(LIT, "extraction.csv"), encoding="utf-8-sig")))
    d1 = {r["key"]: r for r in csv.DictReader(open(os.path.join(LIT, "d1_calls.csv"), encoding="utf-8-sig"))}
    flow = list(csv.DictReader(open(os.path.join(LIT, "screening_flow.csv"), encoding="utf-8-sig")))

    missing = [r["key"] for r in rows if r["key"] not in d1]
    assert not missing, "Rows in extraction.csv lack D1 adjudications: %s" % missing

    yes = [r for r in rows if d1[r["key"]]["d1"] == "yes"]
    no = [r for r in rows if d1[r["key"]]["d1"] == "no"]
    ins = [r for r in rows if d1[r["key"]]["d1"] == "insufficient"]
    exp = [r for r in yes if d1[r["key"]]["grade"] == "explicit"]
    sys_yes = [r for r in yes if d1[r["key"]]["source"] == "system"]
    man_yes = [r for r in yes if d1[r["key"]]["source"] == "manual"]

    def cnt(rs, col, val="yes"):
        return sum(1 for r in rs if r[col] == val)

    L = []
    A = L.append
    A("# §2.3 Number reconciliation (generated by `scripts_v2/lit_numbers.py`; do not edit manually)\n")
    A("## 1. Screening funnel\n")
    A("| Stage | Count | Notes |")
    A("|---|---|---|")
    for f in flow:
        A("| %s | %s | %s |" % (f["stage"], f["n"], f["note"]))
    A("")
    A("## 2. D1 adjudications (criteria: §2.3 and PROTOCOL §4 I3)\n")
    n = len(rows)
    A("- Total coded rows (including 4 manually read papers): **%d**" % n)
    A("- D1 = yes: **%d** (systematic pool %d, manual reading set %d; explicit construction statements %d, inferred only from “the model consumes sequences” %d)"
      % (len(yes), len(sys_yes), len(man_yes), len(exp), len(yes) - len(exp)))
    A("- D1 = no (explicit negative examples): **%d** — %s" % (len(no), ", ".join(r["key"] for r in no)))
    A("- D1 = insufficient (abstract/full text insufficient for adjudication; excluded from the denominator under E3): **%d**" % len(ins))
    A("")
    A("### Papers with D1 = yes\n")
    A("| key | Source | Grade | Original sentence |")
    A("|---|---|---|---|")
    for r in yes:
        c = d1[r["key"]]
        A("| %s | %s | %s | %s |" % (r["key"], c["source"], c["grade"], c["sentence"][:110].replace("|", "/")))
    A("")
    A("## 3. Disclosure rates (denominator = %d papers with D1 = yes)\n" % len(yes))
    A("| Reported item | Papers | Proportion | 95% CI (Wilson) |")
    A("|---|---|---|")
    items = [("Reports padding/imputation convention for the sequence dimension", "padding_reported"),
             ("States the decision threshold (or how it was selected)", "threshold_reported"),
             ("Reports a standalone FPR value", "fpr_reported"),
             ("Reports an AUC value", "auc_reported"),
             ]
    for label, col in items:
        k = cnt(yes, col)
        A("| %s | %d | %s | %s |" % (label, k, pct(k, len(yes)), pct(k, len(yes)).split("[")[1].rstrip("]") if len(yes) else "-"))
    k_mac = sum(1 for r in yes if "macro-F1" in r["metric"])
    A("| Reports macro-F1 | %d | %s | %s |"
      % (k_mac, pct(k_mac, len(yes)), pct(k_mac, len(yes)).split("[")[1].rstrip("]") if len(yes) else "-"))
    k_seed = sum(1 for r in yes if r["n_seeds"].isdigit())
    A("| Reports the number of seeds used in repeated experiments (specific values) | %d | %s | %s |"
      % (k_seed, pct(k_seed, len(yes)), pct(k_seed, len(yes)).split("[")[1].rstrip("]") if len(yes) else "-"))

    seeds_vals = [r["n_seeds"] for r in yes if r["n_seeds"].isdigit()]
    A("")
    A("- Papers reporting **≥10** seeds: **%d**" % sum(1 for v in seeds_vals if int(v) >= 10))
    A("- Reported seed counts: %s" % (", ".join(sorted(seeds_vals)) if seeds_vals else "none"))
    A("")
    A("## 4. Sensitivity analysis using only the %d papers with explicit construction statements\n" % len(exp))
    A("| Reported item | Papers | Proportion |")
    A("|---|---|---|")
    for label, col in items:
        k = cnt(exp, col)
        A("| %s | %d | %s |" % (label, k, pct(k, len(exp)) if exp else "-"))
    if exp:
        k_seed = sum(1 for r in exp if r["n_seeds"].isdigit())
        A("| Reports the number of seeds used in repeated experiments (specific values) | %d | %s |" % (k_seed, pct(k_seed, len(exp))))
    A("")
    A("## 5. Differences between the systematic pool and manual reading set (must be stated in the manuscript)\n")
    A("- Systematic pool D1 = yes: %d / %d coded rows = %s"
      % (len(sys_yes), len(rows) - len(man_yes), pct(len(sys_yes), len(rows) - len(man_yes))))
    A("- Manual reading set D1 = yes: %d / %d" % (len(man_yes), len(man_yes)))
    A("- **Systematic search did not retrieve these %d papers** (they were references in the initial draft), indicating incomplete recall (PROTOCOL §7, item 1)."
      % len(man_yes))
    A("")
    A("## 6. Observed `T` values (D1 = yes)\n")
    ts = [r["T"] for r in yes]
    tt = sorted(set(t for t in ts if t.isdigit()), key=int)
    A("- Explicit `T`: %s (range %s–%s)" % (", ".join(tt), tt[0] if tt else "-", tt[-1] if tt else "-"))
    A("- `T` = config (configurable, no default reported): %d papers" % sum(1 for t in ts if t == "config"))
    A("- `T` not reported: %d papers" % sum(1 for t in ts if not t.isdigit()))

    txt = "\n".join(L) + "\n"
    open(os.path.join(LIT, "NUMBERS_2_3.md"), "w", encoding="utf-8").write(txt)
    print(txt)


if __name__ == "__main__":
    main()
